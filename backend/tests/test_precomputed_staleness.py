"""
Regression test (audit 2026-10-24, item 9): a precomputed_analyses.json
generated by an older claim_patterns spec_version must be visibly flagged as
stale, not silently served as current.
"""
import json

import services.precomputed_store as ps
import services.claim_patterns as cp


def _reset_state():
    ps._state["data"] = None
    ps._state["mtime"] = 0.0


def test_matching_spec_version_is_not_stale(tmp_path, monkeypatch):
    _reset_state()
    f = tmp_path / "precomputed_analyses.json"
    f.write_text(json.dumps({"generated_at": "2026-10-24T00:00:00Z",
                             "spec_version": cp.SPEC_VERSION, "unbundling": []}))
    monkeypatch.setattr(ps, "_PATH", f)

    info = ps.get_staleness_info()
    assert info["is_stale"] is False
    assert info["file_version"] == cp.SPEC_VERSION


def test_older_spec_version_is_flagged_stale(tmp_path, monkeypatch):
    _reset_state()
    f = tmp_path / "precomputed_analyses.json"
    f.write_text(json.dumps({"generated_at": "2026-07-01T00:00:00Z",
                             "spec_version": "2026-07-01.0", "unbundling": []}))
    monkeypatch.setattr(ps, "_PATH", f)

    info = ps.get_staleness_info()
    assert info["is_stale"] is True
    assert info["file_version"] == "2026-07-01.0"
    assert info["current_version"] == cp.SPEC_VERSION


def test_missing_spec_version_field_is_flagged_stale(tmp_path, monkeypatch):
    _reset_state()
    f = tmp_path / "precomputed_analyses.json"
    f.write_text(json.dumps({"generated_at": "2026-01-01T00:00:00Z", "unbundling": []}))
    monkeypatch.setattr(ps, "_PATH", f)

    info = ps.get_staleness_info()
    assert info["is_stale"] is True
    assert info["file_version"] is None
